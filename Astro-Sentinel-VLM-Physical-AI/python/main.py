"""Astro-Sentinel VLM Droid for Arduino VENTUNO Q / App Lab 0.11+.

Architecture:
  Arduino USB Camera -> local Camera peripheral -> local VLM Brick label
  label + distance only -> Nebius Token Factory / NVIDIA Nemotron
  mood token -> MCU LED-matrix animation + Modulino Buzzer and Vibro

The camera is continuously captured locally. A temporary JPEG is written to
local /tmp only for the documented VisionLanguageModel.chat(images=[path]) API
and deleted immediately after local VLM inference. The image is never sent to
Nebius by this application and is not kept as a project asset.
"""
