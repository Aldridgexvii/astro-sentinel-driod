# Camera stream state. Only the capture thread calls Camera.capture(); the VLM
# worker copies the most recent frame under this lock.
_camera: Camera | None = None
_camera_started = False
_camera_stop = threading.Event()
_frame_lock = threading.Lock()
_latest_frame: Any = None
_latest_frame_at = 0.0
_last_camera_capture_log = 0.0
_last_camera_active_reported: bool | None = None
_last_camera_bridge_error = 0.0

# A single worker serializes VLM + Nebius so model requests never pile up.
_analysis_queue: queue.Queue[tuple[int, float]] = queue.Queue(maxsize=1)
_analysis_busy = threading.Event()
_event_queue: queue.Queue[tuple[Any, ...]] = queue.Queue()

# A session/generation invalidates slow responses after an object leaves the zone.
_session_lock = threading.Lock()
_session_generation = 0
_in_zone = False
_need_initial_analysis = False
_last_job_completed_at = 0.0
_last_reaction_at = 0.0
_last_reaction_state = "IDLE"


# Initialize the Arduino USB camera through App Lab's supported Camera peripheral.
try:
    _camera = Camera(
        CAMERA_SOURCE,
        resolution=(CAMERA_WIDTH, CAMERA_HEIGHT),
        fps=CAMERA_FPS,
    )
    _camera.start()
    _camera_started = True
    print(
        f"[camera] Stream started from {CAMERA_SOURCE} at "
        f"{CAMERA_WIDTH}x{CAMERA_HEIGHT}/{CAMERA_FPS} fps."
    )
except Exception as exc:
    _camera = None
    _camera_started = False
    print(f"[camera] Could not start camera ({type(exc).__name__}: {exc}).")


def camera_capture_loop() -> None:
    """Continuously refresh a bounded in-memory frame buffer without busy-spinning."""
    global _latest_frame, _latest_frame_at, _last_camera_capture_log
    if _camera is None:
        return
    while not _camera_stop.is_set():
        try:
            frame = _camera.capture()
            if frame is not None:
                try:
                    snapshot = frame.copy()
                except Exception:
                    snapshot = frame
                with _frame_lock:
                    _latest_frame = snapshot
                    _latest_frame_at = time.monotonic()
            else:
                now = time.monotonic()
                if now - _last_camera_capture_log > 5.0:
                    print("[camera] No frame yet; waiting for the USB camera stream.")
                    _last_camera_capture_log = now
            # Some backends block inside capture(); others return quickly. This small
            # pause prevents high CPU use if capture() returns immediately.
            _camera_stop.wait(0.035)
        except Exception as exc:
            now = time.monotonic()
            if now - _last_camera_capture_log > 5.0:
                print(f"[camera] Capture error ({type(exc).__name__}: {exc}).")
                _last_camera_capture_log = now
            _camera_stop.wait(0.2)


if _camera_started:
    threading.Thread(target=camera_capture_loop, name="astro-camera-capture", daemon=True).start()


def camera_is_active() -> bool:
    with _frame_lock:
        last_frame_at = _latest_frame_at
    return bool(
        _camera_started
        and last_frame_at > 0
        and (time.monotonic() - last_frame_at) <= CAMERA_ACTIVE_TIMEOUT_SECONDS
    )


def copy_fresh_frame(wait_seconds: float = 1.5) -> Any | None:
    deadline = time.monotonic() + wait_seconds
    while not _camera_stop.is_set() and time.monotonic() < deadline:
        with _frame_lock:
            frame = _latest_frame
            captured_at = _latest_frame_at
            if frame is not None and captured_at and time.monotonic() - captured_at <= CAMERA_ACTIVE_TIMEOUT_SECONDS:
                try:
                    return frame.copy()
                except Exception:
                    return frame
        time.sleep(0.05)
    return None


def save_ephemeral_jpeg(frame: Any) -> str:
    """Write one short-lived JPEG under the app directory for the VLM path API.

    The VLM Brick examples pass image paths from the app's mounted asset area. Keeping
    this temporary file under the app directory makes it accessible to the local Brick;
    the file is deleted immediately when VLM inference returns, before any cloud call.
    """
    jpeg = compress_to_jpeg(frame=frame, quality=JPEG_QUALITY)
    if jpeg is None:
        raise RuntimeError("Camera frame could not be compressed to JPEG")
    payload = jpeg.tobytes() if hasattr(jpeg, "tobytes") else bytes(jpeg)
    temp_dir = Path(__file__).resolve().parent / ".astro_runtime"
    temp_dir.mkdir(parents=True, exist_ok=True)
    fd, path = tempfile.mkstemp(prefix="astro-sentinel-", suffix=".jpg", dir=str(temp_dir))
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(payload)
    except Exception:
        try:
            os.close(fd)
        except OSError:
            pass
        try:
            os.unlink(path)
        except OSError:
            pass
        raise
    return path


def session_is_current(generation: int) -> bool:
    with _session_lock:
        return _in_zone and generation == _session_generation


def ask_nemotron(label: str, distance_mm: float) -> tuple[str, bool]:
    """Send text-only metadata to Nebius; no image/frame is passed to this client."""
    if client is None:
        return "CONFUSED", False
    safe_label = sanitize_vlm_label(label, VLM_MAX_LABEL_WORDS)
    message = f"local_vlm_label={safe_label}; distance_mm={distance_mm:.0f}"
    try:
        response = client.chat.completions.create(
            model=NEBIUS_MODEL,
            messages=[
                {"role": "system", "content": NEMOTRON_SYSTEM_PROMPT},
                {"role": "user", "content": message},
            ],
            temperature=0,
            max_tokens=32,
            extra_body={"chat_template_kwargs": {"enable_thinking": False}},
        )
        raw_reply = response.choices[0].message.content or ""
        mood = parse_mood(raw_reply)
        if mood:
            print(f"[Nemotron] label={safe_label!r}; mood={mood}")
            return mood, True
        print(f"[Nemotron] Unrecognized response {raw_reply[:120]!r}; using CONFUSED.")
    except Exception as exc:
        print(f"[Nemotron] Request failed ({type(exc).__name__}: {exc}); using local fallback.")
    return "CONFUSED", False


def analysis_worker() -> None:
    """Serial worker: local VLM snapshot label, then text-only cloud reasoning."""
    vlm: Any = None
    vlm_error: str | None = VLM_IMPORT_ERROR

    while not _camera_stop.is_set():
        try:
            job = _analysis_queue.get(timeout=0.25)
        except queue.Empty:
            continue
        generation, distance_mm = job
        ephemeral_path: str | None = None
        try:
            if not session_is_current(generation):
                continue
            _event_queue.put(("state", generation, "LABELING"))

            frame = copy_fresh_frame()
            if frame is None:
                _event_queue.put(("camera_error", generation, "No fresh camera frame available."))
                continue

            if VisionLanguageModel is None:
                detail = vlm_error or "VLM Brick import failed"
                print(f"[VLM] Brick unavailable: {detail}")
                _event_queue.put(("vlm_error", generation, detail))
                continue

            if vlm is None:
                try:
                    vlm = VisionLanguageModel(system_prompt=VLM_SYSTEM_PROMPT)
                    vlm_error = None
                    print("[VLM] Local VisionLanguageModel ready.")
                except Exception as exc:
                    vlm_error = f"{type(exc).__name__}: {exc}"
                    print(f"[VLM] Could not initialize local VLM: {vlm_error}")
                    _event_queue.put(("vlm_error", generation, vlm_error))
                    continue

            ephemeral_path = save_ephemeral_jpeg(frame)
            try:
                # Official local VLM Brick API: chat(prompt, images=[path]).
                raw_label = vlm.chat(VLM_USER_PROMPT, images=[ephemeral_path])
            finally:
                # Delete the visual input immediately after local inference. In
                # particular, don't leave it on disk during the Nebius API request.
                try:
                    os.unlink(ephemeral_path)
                    print("[privacy] Ephemeral local JPEG removed after VLM inference.")
                except OSError as exc:
                    print(f"[privacy] Could not remove temporary image: {exc}")
                ephemeral_path = None

            label = sanitize_vlm_label(raw_label, VLM_MAX_LABEL_WORDS)
            print(f"[VLM] Local text label: {label!r}")
            _event_queue.put(("label", generation, label))

            # Briefly show the checkmark so physical feedback makes the perception
            # stage legible before the thinking spinner starts.
            time.sleep(0.35)
            # Don't spend a cloud call or play an out-of-date reaction after the user
            # has removed the object from the trigger zone.
            if not session_is_current(generation):
                print("[pipeline] Object left the interaction zone; stale VLM result discarded.")
                continue

            _event_queue.put(("state", generation, "THINKING"))
            mood, cloud_ok = ask_nemotron(label, distance_mm)
            if session_is_current(generation):
                _event_queue.put(("result", generation, label, mood, cloud_ok))
            else:
                print("[pipeline] Object left during cloud reasoning; stale physical response discarded.")

        except Exception as exc:
            print(f"[pipeline] Analysis failed ({type(exc).__name__}: {exc}).")
            if session_is_current(generation):
                _event_queue.put(("vlm_error", generation, f"{type(exc).__name__}: {exc}"))
        finally:
            if ephemeral_path:
                try:
                    os.unlink(ephemeral_path)
                    print("[privacy] Ephemeral local JPEG removed after VLM inference.")
                except OSError as exc:
                    print(f"[privacy] Could not remove temporary image {ephemeral_path}: {exc}")
            _event_queue.put(("job_finished", generation, time.monotonic()))
            _analysis_queue.task_done()
            _analysis_busy.clear()


threading.Thread(target=analysis_worker, name="astro-vlm-nemotron", daemon=True).start()


def bridge_call(method: str, *args: Any, timeout: float = 1.5) -> Any:
    return Bridge.call(method, *args, timeout=timeout)


_last_bridge_error_at = 0.0
_hardware_status_printed = False
_last_distance_error_at = 0.0
_last_visual_state = "IDLE"
_last_visual_state_at = 0.0


def set_visual_state(name: str) -> None:
    global _last_bridge_error_at, _last_visual_state, _last_visual_state_at
    code = STATE_CODES.get(name, STATE_CODES["CONFUSED"])
    try:
        bridge_call("set_state", code, timeout=1.5)
        _last_visual_state = name
        _last_visual_state_at = time.monotonic()
    except Exception as exc:
        now = time.monotonic()
        if now - _last_bridge_error_at > 5.0:
            print(f"[LED/Bridge] Could not set state {name}: {type(exc).__name__}: {exc}")
            _last_bridge_error_at = now


def report_camera_active(active: bool) -> None:
    global _last_camera_active_reported, _last_camera_bridge_error
    if _last_camera_active_reported is active:
        return
    try:
        bridge_call("set_camera_active", bool(active), timeout=1.5)
        _last_camera_active_reported = active
        if active:
            print("[camera] ACTIVE — blinking onboard camera indicator enabled.")
        else:
            print("[camera] INACTIVE / no fresh frames — crossed-camera indicator enabled.")
    except Exception as exc:
        now = time.monotonic()
        if now - _last_camera_bridge_error > 5.0:
            print(f"[camera] Could not update matrix camera indicator: {type(exc).__name__}: {exc}")
            _last_camera_bridge_error = now


def enqueue_analysis(generation: int, distance_mm: float) -> bool:
    if _analysis_busy.is_set():
        return False
    _analysis_busy.set()
    try:
        _analysis_queue.put_nowait((generation, distance_mm))
        print(f"[sensor] Object in range at {distance_mm:.0f} mm; queued local VLM labelling.")
        set_visual_state("LABELING")
        return True
    except queue.Full:
        _analysis_busy.clear()
        return False


def process_worker_events() -> None:
    global _last_job_completed_at, _last_reaction_at, _last_reaction_state
    while True:
        try:
            event = _event_queue.get_nowait()
        except queue.Empty:
            return

        kind = event[0]
        if kind == "job_finished":
            _last_job_completed_at = float(event[2])
            continue

        generation = int(event[1])
        if not session_is_current(generation):
            continue

        if kind == "state":
            set_visual_state(str(event[2]))
        elif kind == "label":
            label = str(event[2])
            set_visual_state("IDENTIFIED" if label != "unknown" else "CONFUSED")
        elif kind == "camera_error":
            print(f"[camera] {event[2]}")
            set_visual_state("CAMERA_ERROR")
            try:
                bridge_call("play_mood", "CONFUSED", timeout=1.5)
            except Exception:
                pass
        elif kind == "vlm_error":
            print(f"[VLM] {event[2]}")
            set_visual_state("OFFLINE")
            try:
                bridge_call("play_mood", "CONFUSED", timeout=1.5)
            except Exception:
                pass
            _last_reaction_at = time.monotonic()
            _last_reaction_state = "OFFLINE"
        elif kind == "result":
            label, mood, cloud_ok = str(event[2]), str(event[3]), bool(event[4])
            set_visual_state(mood if cloud_ok else "OFFLINE")
            try:
                bridge_call("play_mood", mood, timeout=3.0)
            except Exception as exc:
                print(f"[hardware] Mood feedback failed: {type(exc).__name__}: {exc}")
            print(
                f"[Astro-Sentinel] label={label!r}; mood={mood}; "
                f"cloud={'ok' if cloud_ok else 'fallback'}"
            )
            _last_reaction_at = time.monotonic()
            _last_reaction_state = mood if cloud_ok else "OFFLINE"


def loop() -> None:
    """Fast sensor loop; local VLM/Nemotron run in a separate serial worker."""
    global _hardware_status_printed, _session_generation, _in_zone
    global _need_initial_analysis, _last_reaction_at, _last_reaction_state
    global _last_distance_error_at

    process_worker_events()
    now = time.monotonic()

    try:
        if not _hardware_status_printed:
            print(bridge_call("get_hardware_status", timeout=3.0))
            _hardware_status_printed = True
            set_visual_state("IDLE")

        report_camera_active(camera_is_active())

        distance_raw = bridge_call("get_distance_mm", timeout=0.8)
        distance_mm = float(distance_raw)
        now = time.monotonic()
        if not (0.0 < distance_mm < 10000.0):
            time.sleep(DISTANCE_POLL_INTERVAL_SECONDS)
            return

        with _session_lock:
            currently_in_zone = _in_zone

        if not currently_in_zone and distance_mm <= TRIGGER_DISTANCE_MM:
            with _session_lock:
                _session_generation += 1
                current_generation = _session_generation
                _in_zone = True
                _need_initial_analysis = True
            print(
                f"[sensor] Entered interaction zone at {distance_mm:.0f} mm "
                f"(enter <= {TRIGGER_DISTANCE_MM}; exit >= {EXIT_DISTANCE_MM})."
            )
            _last_reaction_at = 0.0
            _last_reaction_state = "IDLE"

        elif currently_in_zone and distance_mm >= EXIT_DISTANCE_MM:
            with _session_lock:
                _session_generation += 1  # invalidate any late VLM/cloud result
                _in_zone = False
                _need_initial_analysis = False
            print(f"[sensor] Object left interaction zone at {distance_mm:.0f} mm; ready again.")
            set_visual_state("IDLE")
            _last_reaction_at = 0.0
            _last_reaction_state = "IDLE"
            time.sleep(DISTANCE_POLL_INTERVAL_SECONDS)
            return

        with _session_lock:
            currently_in_zone = _in_zone
            current_generation = _session_generation
            need_initial = _need_initial_analysis

        if currently_in_zone and not _analysis_busy.is_set():
            interval_elapsed = (
                _last_job_completed_at <= 0.0
                or now - _last_job_completed_at >= VLM_REPEAT_INTERVAL_SECONDS
            )
            if need_initial or interval_elapsed:
                queued = enqueue_analysis(current_generation, distance_mm)
                if queued:
                    with _session_lock:
                        if _session_generation == current_generation:
                            _need_initial_analysis = False

        if (
            _last_reaction_at > 0
            and now - _last_reaction_at >= REACTION_HOLD_SECONDS
            and not _analysis_busy.is_set()
        ):
            with _session_lock:
                still_inside = _in_zone
            if still_inside and _last_reaction_state != "IDLE":
                set_visual_state("IDLE")
                _last_reaction_state = "IDLE"
                _last_reaction_at = 0.0

    except Exception as exc:
        now = time.monotonic()
        if now - _last_distance_error_at > 5.0:
            print(f"[Bridge/sensor] {type(exc).__name__}: {exc}")
            _last_distance_error_at = now
        time.sleep(0.2)

    time.sleep(DISTANCE_POLL_INTERVAL_SECONDS)


def shutdown() -> None:
    _camera_stop.set()
    try:
        if _camera is not None and _camera_started:
            _camera.stop()
    except Exception as exc:
        print(f"[camera] Stop error: {type(exc).__name__}: {exc}")
    try:
        Bridge.call("set_camera_active", False, timeout=1.0)
        Bridge.call("set_state", STATE_CODES["IDLE"], timeout=1.0)
    except Exception:
        pass


print("Astro-Sentinel VLM Droid starting: VENTUNO Q + Arduino USB Camera + local VLM + Nemotron")
print(
    f"[config] camera={CAMERA_SOURCE} {CAMERA_WIDTH}x{CAMERA_HEIGHT}; "
    f"enter={TRIGGER_DISTANCE_MM} mm; exit={EXIT_DISTANCE_MM} mm; "
    f"VLM repeat={VLM_REPEAT_INTERVAL_SECONDS:.0f}s"
)
print(
    "[privacy] VLM runs locally. A short-lived JPEG is deleted after inference; "
    "Nebius receives only the sanitized text label and distance."
)
if VLM_IMPORT_ERROR:
    print(f"[warning] VLM Brick import failed: {VLM_IMPORT_ERROR}")
else:
    print("[vlm] Using Arduino App Lab VisionLanguageModel Brick; select/download Qwen 3-VL-8B VLM in Brick settings.")
if not _camera_started:
    print("[warning] Camera is unavailable; matrix will show the crossed-camera indicator.")

try:
    App.run(user_loop=loop)
except KeyboardInterrupt:
    print("Astro-Sentinel stopping...")
finally:
    shutdown()
